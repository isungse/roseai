// Pretendard subset for the site. The full variable font is 2 MB; preloaded on every page it held mobile
// LCP at ~13 s (works W9). This keeps only the characters the site's copy and code use, plus printable
// ASCII, with every weight axis intact. Re-run after copy changes:
//
//   npm run font:subset
//
// lib/fonts.ts fails the build when messages/ko.json uses a character outside the subset.
import fs from "node:fs";
import path from "node:path";
import subsetFont from "subset-font";

const ROOT = path.resolve(import.meta.dirname, "..", "..");
const FULL = path.join(ROOT, "node_modules/pretendard/dist/web/variable/woff2/PretendardVariable.woff2");
const OUT_FONT = path.join(import.meta.dirname, "PretendardVariable.subset.woff2");
const OUT_CHARS = path.join(import.meta.dirname, "subset-chars.ts");
const SOURCES = ["messages", "app", "components", "lib"];

const chars = new Set();
for (let c = 0x20; c <= 0x7e; c++) chars.add(String.fromCharCode(c));
const scan = (dir) => {
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const file = path.join(dir, entry.name);
    if (entry.isDirectory()) {
      // The generated character list must not feed itself.
      if (file !== import.meta.dirname) scan(file);
    } else if (/\.(tsx?|json)$/.test(entry.name)) {
      for (const ch of fs.readFileSync(file, "utf8")) if (ch.codePointAt(0) > 0x7e) chars.add(ch);
    }
  }
};
for (const source of SOURCES) scan(path.join(ROOT, source));

const text = [...chars].sort().join("");
const font = await subsetFont(fs.readFileSync(FULL), text, { targetFormat: "woff2" });
fs.writeFileSync(OUT_FONT, font);
fs.writeFileSync(
  OUT_CHARS,
  `// Generated by app/fonts/subset.mjs — the characters in PretendardVariable.subset.woff2. Do not edit.\n` +
    `export const SUBSET_CHARS = ${JSON.stringify(text)};\n`,
);
console.log(`[font] ${chars.size} characters → ${path.relative(ROOT, OUT_FONT)} (${(font.length / 1024).toFixed(0)} KB)`);
